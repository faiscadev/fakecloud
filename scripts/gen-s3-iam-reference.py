#!/usr/bin/env python3
"""Regenerate the S3 IAM reference table fakecloud vendors.

Source of truth: the AWS service authorization reference for Amazon S3, the
machine-readable form of "Actions, resources, and condition keys for Amazon S3":

    https://servicereference.us-east-1.amazonaws.com/v1/s3/s3.json

It lists every S3 policy action with the resource types it is authorized on,
and maps each API operation to the actions that can authorize it (the union of
the required and the conditionally required ones -- which of them a given
request needs is decided by `fakecloud_s3`'s `iam_actions` module, reviewed
against the user guide's "Required permissions for Amazon S3 API operations").

The script reads a downloaded copy (never fetches) and writes
`crates/fakecloud-s3/src/service/iam_reference.rs`. Deterministic: actions and
operations sorted, so regenerating from an unchanged file is a no-op.

    curl -sSfo s3.json https://servicereference.us-east-1.amazonaws.com/v1/s3/s3.json
    python3 -I scripts/gen-s3-iam-reference.py s3.json \\
        [--out crates/fakecloud-s3/src/service/iam_reference.rs]
"""
import argparse
import json
import pathlib
import re

DEFAULT_OUT = "crates/fakecloud-s3/src/service/iam_reference.rs"
NAME = re.compile(r"^[A-Za-z0-9*-]+$")


def resource_kind(resources):
    """The resource an action is authorized on, as fakecloud builds its ARN."""
    names = {r["Name"] for r in resources}
    if not names:
        return "Account"
    if "object" in names:
        return "Object"
    if "bucket" in names:
        return "Bucket"
    return "Other"


def checked(name):
    if not NAME.match(name):
        raise SystemExit(f"unexpected name in reference: {name!r}")
    return name


def build(ref):
    if ref.get("Name") != "s3":
        raise SystemExit("not the S3 service reference")
    actions = sorted(
        (checked(a["Name"]), resource_kind(a.get("Resources") or []))
        for a in ref["Actions"]
    )
    operations = []
    for op in ref["Operations"]:
        authorized = sorted(
            {
                f'{checked(a["Service"])}:{checked(a["Name"])}'
                for a in op.get("AuthorizedActions") or []
            }
        )
        operations.append((checked(op["Name"]), authorized))
    operations.sort()

    out = [
        "//! The AWS service authorization reference for Amazon S3, vendored.",
        "//!",
        "//! GENERATED by `scripts/gen-s3-iam-reference.py` from",
        "//! <https://servicereference.us-east-1.amazonaws.com/v1/s3/s3.json>.",
        "//! Do not edit by hand; regenerate instead.",
        "",
        "/// The resource an S3 policy action is authorized on.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub(crate) enum ResourceKind {",
        "    /// `arn:aws:s3:::bucket/key`.",
        "    Object,",
        "    /// `arn:aws:s3:::bucket`.",
        "    Bucket,",
        "    /// No resource type: authorized on `*`.",
        "    Account,",
        "    /// Another resource type (access point, job, Storage Lens, ...).",
        "    Other,",
        "}",
        "",
        "/// Every `s3:` policy action and the resource it is authorized on,",
        "/// sorted by action name.",
        "pub(crate) const ACTION_RESOURCES: &[(&str, ResourceKind)] = &[",
    ]
    out += [f'    ("{name}", ResourceKind::{kind}),' for name, kind in actions]
    out += [
        "];",
        "",
        "/// Every API operation and the policy actions that can authorize it",
        "/// (required and conditionally required), sorted by operation name.",
        "#[cfg(test)]",
        "pub(crate) const OPERATION_ACTIONS: &[(&str, &[&str])] = &[",
    ]
    for name, authorized in operations:
        joined = ", ".join(f'"{a}"' for a in authorized)
        out.append(f'    ("{name}", &[{joined}]),')
    out += ["];", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("reference", help="downloaded s3.json")
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args()
    with open(args.reference, encoding="utf-8") as f:
        ref = json.load(f)
    pathlib.Path(args.out).write_text(build(ref), encoding="utf-8")


if __name__ == "__main__":
    main()
