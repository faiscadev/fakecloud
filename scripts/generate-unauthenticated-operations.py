#!/usr/bin/env python3
"""Regenerate the unauthenticated-operation table
(`crates/fakecloud-core/src/anonymous_gen.rs`).

An operation needs no credentials when its Smithy model marks it
`smithy.api#optionalAuth`, or gives it an empty `smithy.api#auth` list (or its
service does, and the operation does not override it). Each row is keyed by
the service's SigV4 signing name (`aws.auth#sigv4.name`), which is the name
fakecloud registers the service under. Dispatch serves an unsigned request to
one of these operations without refusing it for its missing credentials. Run
after refreshing the models:

    python3 scripts/generate-unauthenticated-operations.py
"""
import glob
import json
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "crates", "fakecloud-core", "src", "anonymous_gen.rs")


def unauthenticated(model_path):
    shapes = json.load(open(model_path)).get("shapes", {})
    services = [(sid, s) for sid, s in shapes.items() if s.get("type") == "service"]
    if not services:
        return []
    _, service = services[0]
    traits = service.get("traits", {})
    signing = traits.get("aws.auth#sigv4", {}).get("name")
    if not signing:
        return []
    service_unauthenticated = traits.get("smithy.api#auth") == []
    rows = []
    for sid, shape in shapes.items():
        if shape.get("type") != "operation":
            continue
        op_traits = shape.get("traits", {})
        auth = op_traits.get("smithy.api#auth")
        if (
            "smithy.api#optionalAuth" in op_traits
            or auth == []
            or (auth is None and service_unauthenticated)
        ):
            rows.append((signing, sid.split("#")[1]))
    return rows


def main():
    rows = sorted(
        {
            row
            for path in glob.glob(os.path.join(REPO, "aws-models", "*.json"))
            for row in unauthenticated(path)
        }
    )
    lines = [
        "// @generated by scripts/generate-unauthenticated-operations.py from",
        "// aws-models/*.json. Do not edit by hand; rerun after a model refresh.",
        "",
        "/// `(service, operation)` for every operation a Smithy model marks",
        "/// `smithy.api#optionalAuth` or `smithy.api#auth: []`, by the service's",
        "/// SigV4 signing name. Sorted.",
        "pub(crate) const UNAUTHENTICATED_OPERATIONS: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{svc}", "{op}"),' for svc, op in rows]
    lines += ["];", ""]
    open(OUT, "w").write("\n".join(lines))
    subprocess.run(["rustfmt", "--edition", "2021", OUT], check=True)
    print(f"{len(rows)} unauthenticated operations")


if __name__ == "__main__":
    sys.exit(main())
