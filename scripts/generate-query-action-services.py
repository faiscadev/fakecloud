#!/usr/bin/env python3
"""Regenerate the Query-action routing table
(`crates/fakecloud-core/src/query_actions_gen.rs`).

An unsigned Query request (`Action=...` in the query string or a form body)
names no service by its signature, and on fakecloud's shared listener often by
no host either. Every operation of an awsQuery / ec2Query /
awsQueryCompatible model whose name belongs to exactly one such service maps
to that service, by its SigV4 signing name (DocumentDB and Neptune sign as
`rds` and share its operation names). Names several services share are left
out: they route only by signature or host. Run after refreshing the models:

    python3 scripts/generate-query-action-services.py
"""
import glob
import json
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "crates", "fakecloud-core", "src", "query_actions_gen.rs")
QUERY_PROTOCOLS = (
    "aws.protocols#awsQuery",
    "aws.protocols#ec2Query",
    "aws.protocols#awsQueryCompatible",
)


def query_operations(model_path):
    shapes = json.load(open(model_path)).get("shapes", {})
    services = [s for s in shapes.values() if s.get("type") == "service"]
    if not services:
        return None, []
    traits = services[0].get("traits", {})
    if not any(p in traits for p in QUERY_PROTOCOLS):
        return None, []
    signing = traits.get("aws.auth#sigv4", {}).get("name")
    ops = [sid.split("#")[1] for sid, s in shapes.items() if s.get("type") == "operation"]
    return signing, ops


def main():
    owners = {}
    for path in glob.glob(os.path.join(REPO, "aws-models", "*.json")):
        service, ops = query_operations(path)
        if not service:
            continue
        for op in ops:
            owners.setdefault(op, set()).add(service)
    rows = sorted((op, next(iter(s))) for op, s in owners.items() if len(s) == 1)
    lines = [
        "// @generated by scripts/generate-query-action-services.py from",
        "// aws-models/*.json. Do not edit by hand; rerun after a model refresh.",
        "",
        "/// `(Action, service)` for every awsQuery / ec2Query / awsQueryCompatible",
        "/// operation name exactly one service has, by its SigV4 signing name.",
        "/// Sorted by action.",
        "pub(crate) const QUERY_ACTION_SERVICES: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{op}", "{svc}"),' for op, svc in rows]
    lines += ["];", ""]
    open(OUT, "w").write("\n".join(lines))
    subprocess.run(["rustfmt", "--edition", "2021", OUT], check=True)
    print(f"{len(rows)} actions")


if __name__ == "__main__":
    sys.exit(main())
